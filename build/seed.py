def work_content(w):
    parts = [para('<a href="#gallery">Gallery</a> / <a href="#info">Info</a>', className='is-style-tabs')]
    if w['nums']:
        parts.append(with_id(group(J(*[out_cell('drift-%d.jpg' % n, 'No. %d' % n, 'Drift output %d, flow lines in black and red on off-white paper' % n) for n in w['nums']]),
                           className='is-style-sheet', align='wide', anchor='gallery', layout={'type': 'grid', 'columnCount': 4, 'minimumColumnWidth': '9rem'}), 'gallery'))
    else:
        parts.append(with_id(group(image(w['img'], '%s, %s: a pen drawing on off-white paper' % (w['t'], w['year']), w['t']), className='is-style-sheet', align='wide', anchor='gallery',
                           layout={'type': 'grid', 'columnCount': 2, 'minimumColumnWidth': '14rem'}), 'gallery'))
    parts.append(with_id(group(J(heading('Info', 2, fontSize='x-large'), para(w['statement'], fontSize='large'), info_table(w['info'])), anchor='info', className='is-style-rule-top'), 'info'))
    return J(*parts)


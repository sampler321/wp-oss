# Design note (seed, idea 011, generative / creative-code artist)
# Direction: plotter sheet. The site reads like a sheet of numbered outputs pulled off a pen plotter: square drawings
# in a contact-sheet grid ruled with 1px lines, each labelled with its iteration number, and a work page split into
# Gallery and Info.
# Fonts: Tilt Neon (display, claimed in demos/seed/fonts-claim.txt; its monoline strokes look like one pen line) +
# Mona Sans (body). No monospace: numbers use tabular figures in the body face.
# Palette: plotter paper #F6F5F1, pen black #141414, pen red #B8391A (links only), sheet grey #EAE8E1, rule #BDB9AE.
# Layout idea: grids with 1px gaps over a rule-coloured background, so every output sits in its own cell like a
# contact sheet; the category tabs are plain slash-separated links; the demo outputs are generated by
# build/seed_outputs.py so they are real numbered iterations of three small algorithms.

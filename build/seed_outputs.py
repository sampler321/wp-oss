# Generates the demo "outputs" for the seed theme: plotter-style drawings made by small algorithms, so the demo
# shows numbered iterations of one algorithm the way a generative artist's site does. Not AI: plain maths, drawn with
# PIL. Output: themes/seed/assets/images/<series>-<n>.jpg and credits in themes/seed/.images.json (CC0, WP-OSS).
# Run: python3 build/seed_outputs.py
import json, math, os, random
from PIL import Image, ImageDraw

OUT = os.path.join('themes', 'seed', 'assets', 'images')
PAPER, INK, RED = (246, 245, 241), (20, 20, 20), (210, 70, 30)
SS = 2  # supersample


def canvas(w, h):
    im = Image.new('RGB', (w * SS, h * SS), PAPER)
    return im, ImageDraw.Draw(im)


def save(im, name, w, h, title):
    im = im.resize((w, h), Image.LANCZOS)
    im.save(os.path.join(OUT, name + '.jpg'), quality=82, optimize=True)
    CREDITS[name] = {'title': title, 'creator': 'WP-OSS (generated by build/seed_outputs.py)', 'license': 'CC0', 'url': 'https://github.com/sampler321/wp-oss/blob/main/build/seed_outputs.py'}


def field(seed):
    r = random.Random(seed)
    k = [(r.uniform(0.6, 2.4), r.uniform(0.6, 2.4), r.uniform(0, 6.28), r.uniform(0.3, 1.0)) for _ in range(4)]
    return lambda x, y: sum(a * math.sin(fx * x * 3 + p) * math.cos(fy * y * 3 - p) for fx, fy, p, a in k)


def drift(seed, name, n):
    W = H = 1200
    im, d = canvas(W, H)
    f = field(seed)
    r = random.Random(seed * 7)
    m = 90 * SS
    for i in range(1400):
        x, y = r.uniform(0, 1), r.uniform(0, 1)
        pts = []
        for _ in range(r.randint(30, 90)):
            a = f(x, y) * math.pi
            x += math.cos(a) * 0.004
            y += math.sin(a) * 0.004
            if not (0 < x < 1 and 0 < y < 1):
                break
            pts.append((m + x * (W * SS - 2 * m), m + y * (H * SS - 2 * m)))
        if len(pts) > 3:
            d.line(pts, fill=RED if i % 17 == 0 else INK, width=2 * SS if i % 17 == 0 else SS + 1)
    save(im, name, W, H, 'Drift #%d' % n)


def knot(seed, name, n):
    W = H = 1200
    im, d = canvas(W, H)
    r = random.Random(seed)
    f1, f2, f3, f4 = r.choice([2, 3]), r.choice([2, 3]) + r.uniform(-0.02, 0.02), r.choice([2, 3, 4]) + r.uniform(-0.02, 0.02), 2
    p1, p2, p3 = r.uniform(0, 3.14), r.uniform(0, 3.14), r.uniform(0, 3.14)
    dmp = 0.0035
    pts = []
    for i in range(24000):
        t = i * 0.02
        e = math.exp(-dmp * t)
        x = e * (math.sin(f1 * t + p1) + math.sin(f3 * t + p3)) / 2
        y = e * (math.sin(f2 * t + p2) + math.sin(f4 * t)) / 2
        pts.append((W * SS / 2 + x * W * SS * 0.42, H * SS / 2 + y * H * SS * 0.42))
    d.line(pts, fill=INK, width=SS)
    save(im, name, W, H, 'Knot #%d' % n)


def tiles(seed, name, n):
    W = H = 1200
    im, d = canvas(W, H)
    r = random.Random(seed)
    cell = 60 * SS
    for gx in range(0, W * SS, cell):
        for gy in range(0, H * SS, cell):
            col = RED if r.random() < 0.08 else INK
            if r.random() < 0.5:
                d.arc([gx - cell / 2, gy - cell / 2, gx + cell / 2, gy + cell / 2], 0, 90, fill=col, width=3 * SS)
                d.arc([gx + cell / 2, gy + cell / 2, gx + cell * 1.5, gy + cell * 1.5], 180, 270, fill=col, width=3 * SS)
            else:
                d.arc([gx + cell / 2, gy - cell / 2, gx + cell * 1.5, gy + cell / 2], 90, 180, fill=col, width=3 * SS)
                d.arc([gx - cell / 2, gy + cell / 2, gx + cell / 2, gy + cell * 1.5], 270, 360, fill=col, width=3 * SS)
    save(im, name, W, H, 'Tiles #%d' % n)


CREDITS = {}
os.makedirs(OUT, exist_ok=True)
for n in (725, 680, 529, 412, 301, 118, 77, 12):
    drift(n, 'drift-%d' % n, n)
for n in (41, 17):
    knot(n, 'knot-%d' % n, n)
for n in (9, 3):
    tiles(n, 'tiles-%d' % n, n)
cp = os.path.join('themes', 'seed', '.images.json')
existing = json.load(open(cp)) if os.path.exists(cp) else {}
existing.update(CREDITS)
json.dump(existing, open(cp, 'w'), indent=2, ensure_ascii=False)
print('generated', len(CREDITS), 'outputs')

<h3 class="wp-block-heading">Kiruga washing station, Nyeri</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p class="">Kiruga is run by a farmers' cooperative of about 900 members, most with fewer than 300 trees. Cherries are delivered in the afternoon, sorted by hand, pulped and fermented twice before drying on raised beds for 12 to 18 days.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p class="">We buy through Falcon Specialty and have bought from Kiruga three years running. The factory manager, Joseph Mwangi, sends us photos of the drying beds, which is how we know the harvest is late this year.</p>

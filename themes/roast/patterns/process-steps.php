<h3 class="wp-block-heading">What "washed, double fermented" means</h3>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li>Ripe cherries are picked and sorted by hand.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>The skin and fruit are pulped off the seed.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>The seeds ferment in tanks for about 24 hours, are washed, then ferment again under clean water.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>They dry on raised beds for 12 to 18 days, turned by hand.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>The dried parchment rests for a month before milling and export.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list -->

<h3 class="wp-block-heading">Water matters more than you think</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p class="">Liverpool tap water is soft, which suits light roasts. If your kettle furs up, use a jug filter or bottled water with low minerals. Don't use distilled water: the coffee tastes flat.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"fontSize":"small"} -->
<p class="has-small-font-size">Use water just off the boil for light roasts and a minute off the boil for darker ones.</p>

<h3 class="wp-block-heading">A week in a chapel</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We recorded Slack Water in seven days at St Peter's, Heysham, with the pews pushed back and the amps pointing at the organ. Jonny Rees brought two microphones and a tape machine. Most songs are the third take.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The church charged us £40 a day and asked us to stop at 6pm for choir practice. You can hear the tide on Last Boat Out if you turn it up.</p>

<div class="wp-block-column" style="flex-basis:58%"><!-- wp:paragraph {"fontSize":"large"} -->
<p class="has-large-font-size">Heysham Ferry are three people from Morecambe who play loud songs about the sea not quite reaching the promenade. Cat Lomax sings and plays guitar, Dev Mistry plays bass, Ollie Brannan plays drums and drives the van.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>They met at the Platform in 2018, put out Promenade in 2021 and have played 214 shows since, most of them in rooms that hold under 300 people. Slack Water, their second album, is out on 14 November on Saltpan Records.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>They don't play festivals that don't pay the support acts.</p>

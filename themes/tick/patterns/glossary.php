<h2 class="wp-block-heading">Words we use in estimates</h2>
<!-- /wp:heading -->

<!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">Bush</h4>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A brass tube pressed into a worn pivot hole so the wheel runs true again. Included in our clock prices.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">Escapement</h4>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The part that lets the gear train move on one tooth at a time. It makes the tick.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">In beat</h4>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>When the tick and the tock are evenly spaced. A clock out of beat stops within a day.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">Mainspring</h4>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The coiled spring that stores the power in a watch or spring-driven clock.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">Suspension spring</h4>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The thin strip the pendulum hangs from. It breaks more often than anything else, and costs 40 zł.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">Grande sonnerie</h4>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A clock or watch that strikes the hours and quarters at every quarter. Loud, and rare.</p>
<!-- /wp:paragraph -->

<h3 class="wp-block-heading">Looking after a clock at home</h3>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Wind it on the same day each week. Eight-day clocks run eight days so you have one day of grace.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Never turn the hands backwards on a striking clock.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Keep it level. A clock that stops after a house move is usually just out of beat.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Don't oil it yourself. Household oil turns to glue within a year.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Service every eight to ten years for clocks, five to seven for mechanical watches.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

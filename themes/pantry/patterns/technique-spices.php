<h3 class="wp-block-heading">How to toast whole spices</h3>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li>Use a dry frying pan over a medium heat. No oil.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Add the seeds and shake the pan every 20 seconds.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>They're done when they smell strong and the cumin darkens a shade, about 2 minutes.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Tip them straight onto a plate. The pan keeps cooking them.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list -->

<!-- wp:paragraph {"fontSize":"small"} -->
<p class="has-small-font-size">Burnt cumin tastes bitter all the way through a dish. If in doubt, start again: it costs 10p.</p>

<h3 class="wp-block-heading">Preserved lemons, and where to find them</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p class="">Salt-cured lemons, soft enough to chop rind and all. I use only the rind and throw away the pulp. A jar keeps for a year in the fridge once opened.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p class="">Most big supermarkets sell them near the olives. The small ones from Moroccan shops are better and half the price. Or make them: 6 lemons, 150g salt, a clean jar and a month.</p>

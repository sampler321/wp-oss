<h3 class="wp-block-heading">Questions</h3>
<!-- /wp:heading -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can a freelancer use a client’s licence?</summary><!-- wp:paragraph -->
<p class="">No. The licence belongs to whoever pays for it. If you are designing for a client, the client should buy it, or you buy it and transfer it to them. Transfers are free.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do I need a web licence for images of text?</summary><!-- wp:paragraph -->
<p class="">No. A JPEG or PNG of the type is covered by the desktop licence. You need a web licence when the font file is served to browsers.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I edit the fonts?</summary><!-- wp:paragraph -->
<p class="">You may edit them for your own use, for example to draw a custom ligature for a logo. You may not sell or share the edited files.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What if I go over my page views?</summary><!-- wp:paragraph -->
<p class="">Upgrade when you notice. We do not audit anyone and we do not charge back-dated fees.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

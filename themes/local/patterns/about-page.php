<p class="has-large-font-size">Frome Survey started in 2021 after the town's weekly paper stopped covering council meetings. Three of us began by sitting in on the planning committee and posting what was decided. There are now four staff and about 30 volunteers who take notes.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We report on Frome and the parts of Somerset Council that affect it. We don't cover national news, and we don't run press releases unchecked. Our house rule is that every number links to where it came from, and if we can't show the source, we say why.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We think the planning committee is the most important meeting in town and the least attended. If you only read one thing we publish, make it the planning notes.</p>
<!-- /wp:paragraph -->


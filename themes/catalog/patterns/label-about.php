<h2 class="wp-block-heading">A label in a spare room</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Hiss Tapes started in 2016 when Ailsa Kerr dubbed 40 copies of her friend Mira's loop recordings for a gig at Leith Depot and sold all of them. Now there are two of us: Ailsa runs the label and Callum Frew does the J-cards, the post and the shop.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We put out tapes because they are cheap enough to take a chance on, and because people actually keep them. We do some vinyl when a record is selling well enough to pay for a pressing, which is roughly one in four.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Nobody here is paid for it, yet. Artists get half of what their tape makes after costs, paid every June.</p>

<h2 class="wp-block-heading">Sending us a demo</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p class="">We listen to demos on the first Monday of the month, with tea, all the way through. Send a private Bandcamp or SoundCloud link to <a href="mailto:demos@example.com">demos@example.com</a>. Please do not attach files.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p class="">We release four or five tapes a year, so most of what we hear we cannot put out, even when we love it. We reply to everyone, eventually. It can take two months.</p>
<!-- /wp:paragraph -->


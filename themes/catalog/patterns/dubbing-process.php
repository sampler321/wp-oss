<h3 class="wp-block-heading">Dubbed in real time</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p class="">Every tape is copied at normal speed from a master on two Nakamichi decks, twelve at a time. It takes a Saturday to do a run of 100. High-speed duplicators are quicker and we have one, but the top end suffers, so it only makes test copies.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p class="">J-cards are printed on a risograph at Out of the Blue on Dalmeny Street, two colours, on 170gsm card. Shells come from a factory in Poland in six colours.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"fontSize":"small","textColor":"muted"} -->
<p class="has-muted-color has-text-color has-small-font-size">We use chrome (Type II) tape. It costs us 40p more per copy and it is worth it.</p>

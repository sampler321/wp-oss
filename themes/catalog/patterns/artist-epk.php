<!-- wp:paragraph -->
<p>Mira Oduya is a Scottish musician who makes long pieces from tape loops recorded along the Forth estuary. Her second tape for Hiss, <em>Salt rooms</em>, was dubbed onto chrome tape in an edition of 100. She plays live seated, with two Walkmans, a mixer and a borrowed PA.</p>

<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I return a tape?</summary><!-- wp:paragraph -->
<p class="">If it arrives broken or chewed, yes: send a photo and we post another. We cannot take back opened tapes otherwise, because we dub them to order.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you ship to the US?</summary><!-- wp:paragraph -->

<p class="has-large-font-size">Hana Mirza weaves on a floor loom she built from a bed frame. Ciarán Doyle films rivers at the point where they stop being counted as rivers. For six weeks the two of them share the long room, with a curtain of monofilament down the middle that you can walk through.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The show started as a conversation at a members’ crit in 2024. Hana wanted to hang something that you could not see from the door. Ciarán wanted a screen you had to walk round. The curtain does both, badly and on purpose.</p>

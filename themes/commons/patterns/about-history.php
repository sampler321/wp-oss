<h2 class="wp-block-heading has-x-large-font-size">A dye works, then a gallery</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Nine artists took the lease on 41 Mabgate in 2011 because it was cheap and had a big room with no pillars. They painted it, called the first show No. 1, and kept counting.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Fifteen years on there are 14 studios upstairs, a gallery downstairs and 184 shows behind us. We still have no director and no paid staff. Everything is done by a committee of six who change every two years.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We would rather show one odd thing well than six safe things. That has cost us two grants and we would do it again.</p>

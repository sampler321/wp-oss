<p class="has-large-font-size">Ingrid Sandvik and Tunde Ogunleye met at a letterpress workshop in 2011 and started the studio three years later in a back room of the old Moorhouse print works on Mabgate. There are seven of us now, one dog on Wednesdays and a Heidelberg platen that still runs.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Most of our clients sell something you can hold or visit: coffee, beer, books, tickets, soup. We like working with the people who make the thing, and with the printers and sign painters who finish the job. Our opinion, for what it is worth: one well printed menu does more for a café than a 60-page brand guidelines PDF, so we make the menu first.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We don't take on crypto, gambling or oil companies. We close for two weeks at Christmas and for most of August.</p>

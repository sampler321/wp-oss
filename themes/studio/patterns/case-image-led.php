<p class="has-large-font-size">Casa Ribeiro has sold bifanas and soup on Harrogate Road since 1998. The awning had faded to pink and the menu was a laminated A3 sheet. Luis Ribeiro wanted it to look like the place his father opened, only readable from the bus stop.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We drew the lettering from a 1960s Lisbon price board Luis kept in the cellar, then handed the drawings to Beth Wray, who painted the awning and the pillars on site over three days in March. The paper menu is printed on 120gsm uncoated stock and replaced every Monday.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>What we would change: the pillar lists prices, and prices change. Next time the prices go on a chalk panel and only the dishes stay painted.</p>

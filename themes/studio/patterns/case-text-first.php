<h3 class="wp-block-heading">The brief</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Kirkgate Law Library had 140 red volumes of court reports and no way to find year 2009 without pulling six of them out. The budget covered new spine labels, nothing else.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">What we did</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A spine system set in one weight, with the year at 60pt so it reads from the reading tables. Volume numbers sit in the same place on every spine. The labels are printed on self-adhesive book cloth by a binder in Otley.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">What we would do differently</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Test the gold foil under the library lights first. Two shelves glare at 4pm in winter.</p>

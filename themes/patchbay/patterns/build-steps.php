<h3 class="wp-block-heading">Build order</h3>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li>Resistors first, lowest profile, so the board sits flat on the bench.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Diodes and IC socket next. Check the band on each diode against the silkscreen.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Film capacitors, then electrolytics. Long leg to the square pad.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Transistors last before the pots. Keep the iron on each leg for three seconds at most.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Pots and LED go on after the board is in the enclosure, so everything lines up with the holes.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Before power: check for bridges under a lamp. Then 9V, then a guitar.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list -->

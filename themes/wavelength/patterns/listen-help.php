<h2 class="wp-block-heading">Help with listening</h2>
<!-- /wp:heading -->

<!-- wp:details -->
<details class="wp-block-details"><summary>I can't get 104.6 FM in my house.</summary><!-- wp:paragraph -->
<p class="">The signal comes from a mast on Heptonstall Road, so it is strong in the valley bottom and weak on the tops and behind Stoodley Pike. Try the radio near a window facing the valley, or listen online.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Are you on DAB?</summary><!-- wp:paragraph -->
<p class="">Not yet. DAB for small stations in the valley is planned for 2027. We will say on air when it happens.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How do I listen on a smart speaker?</summary><!-- wp:paragraph -->
<p class="">Say "play Calder Valley Radio". If it plays something else, say "play Calder Valley Radio on TuneIn".</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>I missed a programme. Can I hear it again?</summary><!-- wp:paragraph -->
<p class="">Most talk programmes go on the <a href="/news/">news and programmes page</a> the next day, for four weeks. Music programmes do not, because of music licences.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>My neighbour has no internet. Can they still listen?</summary><!-- wp:paragraph -->
<p class="">Yes, on any FM radio. We have ten donated radios to lend. Ring the studio and a volunteer will bring one round.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

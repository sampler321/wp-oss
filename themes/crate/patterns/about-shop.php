<h2 class="wp-block-heading">Crate</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Delroy Mensah opened Crate on Call Lane in 2011 with his own collection and a borrowed till. Ines Barros joined in 2016 to run the jazz and soul, and opened the Hebden Bridge shop in 2021.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We sell used records, mostly, with a wall of new pressings from labels we like. Every used copy is played before it is priced. We think grading by eye is how people end up with a VG+ that sounds like frying bacon.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We do not do online auctions, and we do not hold records without payment.</p>

<h2 class="wp-block-heading">Reading the run-out</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The run-out groove is the smooth band between the last track and the label. The letters scratched or stamped there tell you who cut it and which pressing you have.</p>
<!-- /wp:paragraph -->

<!-- wp:list {"className":"is-style-label"} -->
<ul class="wp-block-list is-style-label"><!-- wp:list-item -->
<li><strong>Matrix number:</strong> the catalogue number plus a side letter, for example ILPS 9624 A.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Stamper code:</strong> small numbers after the matrix; lower usually means earlier.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Cutting engineer:</strong> initials or a name. "Bilbo" and "Porky" are famous UK ones.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Plant marks:</strong> a symbol for the pressing plant, handy for telling UK from EU copies.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list --></div>

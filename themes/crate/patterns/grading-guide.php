<h2 class="wp-block-heading">How we grade</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p class="">Every used record is played on the shop deck before it goes online. We grade the record (media) and the sleeve separately, and we grade down when we are unsure.</p>
<!-- /wp:paragraph -->

<!-- wp:table {"className":"is-style-spec-table"} -->
<figure class="wp-block-table is-style-spec-table"><table class="has-fixed-layout"><thead><tr><th>Grade</th><th>Name</th><th>What it sounds like</th></tr></thead><tbody><tr><td>M</td><td>Mint</td><td>Sealed or never played. We almost never use it for used stock.</td></tr><tr><td>NM</td><td>Near mint</td><td>Played a few times, no marks you can see or hear.</td></tr><tr><td>VG+</td><td>Very good plus</td><td>Light marks under a lamp, silent in play. Most people are happy here.</td></tr><tr><td>VG</td><td>Very good</td><td>Surface noise between tracks and in quiet passages. Music comes first.</td></tr><tr><td>G+</td><td>Good plus</td><td>Constant crackle, still plays through without skips. Priced to match.</td></tr><tr><td>G</td><td>Good</td><td>For completists and DJs who need the one break. Tell us if you want a clip.</td></tr></tbody></table></figure>

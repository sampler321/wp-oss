<h3 class="wp-block-heading">Setting up your files</h3>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li>One file per ink, in greyscale. Black means full ink, 50% grey means 50% ink.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Name each file with the ink colour: <em>zine-cover-blue.pdf</em>, <em>zine-cover-pink.pdf</em>.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>3mm bleed on every side. Keep text 5mm from the edge.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Fine lines under 0.3pt disappear. Text under 7pt fills in.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Riso shifts up to 2mm between layers. Don't design tight butt registration.</li>
<!-- /wp:list-item --></ol>

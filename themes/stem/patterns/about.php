<h2 class="wp-block-heading">Hollyhock</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Rosa Mendes opened Hollyhock in 2016 after eight years working for other florists in the West End. She grew up above her aunt's flower stall in Porto and still buys like her: early, in cash, and with an opinion.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We buy British flowers from May to October and import the rest from the Dutch auctions. We do not use floral foam; everything sits in water, moss or chicken wire.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We do not do funeral tributes with lettering. For that, try Ferns on Well Street, who do it beautifully.</p>

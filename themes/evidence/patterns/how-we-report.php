<h2 class="wp-block-heading">How we report</h2>
<!-- /wp:heading -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>We only make a series when a family member of the person harmed has agreed to it, and we tell them before each episode goes out.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>We don’t play 999 calls, crime scene audio or post-mortem details. We say that a person died and how that affected people.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>We name people who were convicted. We don’t name people who were only suspected, arrested or questioned.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Every claim has a source listed under the episode. When we get something wrong, we fix the audio and the transcript and log it with a date.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>We don’t sell merchandise about real crimes.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->


<p class="has-large-font-size">Nora Bakri (b. 1990, Rotterdam) paints murals and letters. She grew up on the Afrikaanderplein, studied graphic design at the Willem de Kooning Academie and started painting walls when a friend's snack bar needed a sign.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Most of her walls are in Rotterdam. Some are in schools, a few are in back gardens, and one is in Zaragoza because a festival there asked twice. She works with exterior silicate paint and a hired cherry picker, and she paints letters freehand.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>She doesn't paint company logos as murals. A sign, yes. A logo the size of a building, no.</p>

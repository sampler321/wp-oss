<h2 class="wp-block-heading">Questions</h2>
<!-- /wp:heading -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How long does a mural last?</summary><!-- wp:paragraph -->
<p>Outdoors, 10 to 15 years with silicate paint and an anti-graffiti coat. Sun on a south wall fades reds first.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What if someone tags it?</summary><!-- wp:paragraph -->
<p>The anti-graffiti coat lets you wash tags off with hot water. For the first year, I come back once for free.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I choose the design?</summary><!-- wp:paragraph -->
<p>You choose the subject and the colours you can live with. I draw it. If you have a finished design, I am the wrong painter.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you need scaffolding?</summary><!-- wp:paragraph -->
<p>Above 4 metres, a cherry picker, which we hire by the day. You arrange the parking permit with the gemeente.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

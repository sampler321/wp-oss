<p>Radio Havik started in 2018 in the back of Fietsen Bram, a bike shop on the Deliplein that closed the year before. Bram left us the counter, which is now the desk. We are on the internet and DAB+, 24 hours a day, with 61 presenters who all have other jobs.</p>
<!-- /wp:paragraph -->


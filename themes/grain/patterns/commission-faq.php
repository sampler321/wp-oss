<h3 class="wp-block-heading">Questions people ask</h3>
<!-- /wp:heading -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can you make it to fit an odd space?</summary><!-- wp:paragraph -->
<p>That is most of what we do. Send measurements and a photo with a tape measure in it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I supply my own timber?</summary><!-- wp:paragraph -->
<p>Sometimes. If it is a tree from your garden, it needs felling, milling and at least two years of drying before we can use it. We can arrange all three.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What if the wood moves or cracks?</summary><!-- wp:paragraph -->
<p>Solid wood moves with the seasons and we build for that. Joints are guaranteed for ten years. If a top splits because of how we made it, we repair it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you deliver abroad?</summary><!-- wp:paragraph -->
<p>Belgium and Germany, yes, at cost. Further than that we crate it and a carrier takes it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<h3 class="wp-block-heading">What we learned on the platforms</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Four weeks, 11 stations, 46 short interviews and 20 hours of watching people use the machines. Station staff let us stand next to the machines in hi-vis.</p>
<!-- /wp:paragraph -->

<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li><strong>People start with where they are going, not with the ticket type.</strong> 41 of 46 said the destination first when we asked what they wanted.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>The railcard question lost the most people.</strong> It came before the price, so people could not see what a railcard would save them.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Card readers were fine. Cash was the problem.</strong> Only 6% paid in cash, but those journeys took three times as long.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Staff already had a workaround.</strong> They taped a list of fare zones to the side of the machine at Partick.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list -->

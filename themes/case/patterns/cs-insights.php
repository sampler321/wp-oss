<h3 class="wp-block-heading">What we learned</h3>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li><strong>People start with where they are going.</strong> 41 of 46 said the destination first when we asked what they wanted.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>The railcard question lost the most people.</strong> It came before the price, so nobody could see what a railcard would save them.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Card readers were fine. Cash was the problem.</strong> Cash journeys took three times as long.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Staff already had a workaround.</strong> They taped a list of fare zones to the side of the machine at Partick.</li>
<!-- /wp:list-item --></ol>

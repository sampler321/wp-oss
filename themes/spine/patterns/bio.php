<h2 class="wp-block-heading">About</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Tamsin Rourke was born in King’s Lynn in 1974, the daughter of a shrimp fisherman. She worked for twelve years as a court clerk in Peterborough before her first novel, <em>The Salt Road</em>, was published in 2016.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>She has written three Fenland crime novels, two stand-alone novels, a book of travel essays and a memoir about her father. Her books are translated into nine languages. She lives in King’s Lynn with her husband and a lurcher called Pike.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>I write in the mornings and walk the sea wall in the afternoons. I don’t do book blurbs for strangers, and I don’t write about real murders. There are enough invented ones.</p>

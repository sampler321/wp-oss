<div class="wp-block-group is-style-swatch-orange"><!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">If your dog already has a collar</h4>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p class="">Lay it flat. Measure from the end of the buckle to the hole you use now. Buy the size whose range has that number near the middle.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group --></div>
<!-- /wp:column -->

<!-- wp:column -->
<div class="wp-block-column"><!-- wp:group {"className":"is-style-swatch-sky","layout":{"type":"default"}} -->
<div class="wp-block-group is-style-swatch-sky"><!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">If they don't</h4>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p class="">Measure around the neck where a collar sits, with a soft tape. Add 5 cm, or two fingers flat under the tape. That is your collar length.</p>
<!-- /wp:paragraph --></div>

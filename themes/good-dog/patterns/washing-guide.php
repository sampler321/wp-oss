<div class="wp-block-column"><!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li>Unzip the cover and shake it out outside. Then shake it out again.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Wash at 40°C with a normal non-bio powder. Skip fabric softener: it makes the cotton hold on to hair.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Tumble dry low, or line dry. The cover goes back on easier while it is still slightly damp.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>The inner cushion is wipe clean. If it needs a proper wash, take it to a launderette with a big machine.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list -->


<div class="wp-block-column"><!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">1. Nose to tail</h4>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p class="">With the dog standing, measure from the tip of the nose to the base of the tail. Leave the tail out. It has its own plans.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:column -->

<!-- wp:column -->
<div class="wp-block-column"><!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">2. Top of head to floor</h4>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p class="">Measure the dog standing, from the top of the head to the floor. This tells you how tall the raised edge should be for a chin rest.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:column -->

<!-- wp:column -->
<div class="wp-block-column"><!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">3. Times 1.25</h4>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p class="">Multiply the nose-to-tail number by 1.25. That is the smallest inside length that lets your dog stretch out fully.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:column --></div>
<!-- /wp:columns -->

<!-- wp:group {"className":"is-style-swatch-yellow","layout":{"type":"default"}} -->
<div class="wp-block-group is-style-swatch-yellow"><!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">Worked example: Mabel, a dachshund</h4>
<!-- /wp:heading -->

<!-- wp:paragraph {"fontSize":"small"} -->
<p class="has-small-font-size">Nose to base of tail: 52 cm. 52 × 1.25 = <strong>65 cm</strong>. The small bed is 70 cm inside, so Mabel gets a small. She also sleeps curled up most nights, but she likes the option.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->


<p class="has-large-font-size">Edie Achterberg (b. 1988, Groningen) trained at the School of Jewellery in Birmingham and spent six years at a Hatton Garden workshop setting other people's diamonds. She opened her own bench on Magdalen Street, Norwich, in 2019.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p class="">She works alone, with Brass the whippet, in a first-floor room above a violin repairer. Most of her work is wedding and engagement rings, and remodelling family jewellery into something people will actually wear.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p class="">She makes everything by hand, except the casting. She does not sell other people's work, does not work in rose gold and closes the workshop for the whole of August.</p>

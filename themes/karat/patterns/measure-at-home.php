<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li>Wrap a strip of paper round the base of the finger, not too tight.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Mark where it overlaps and measure the length in millimetres.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Find the nearest circumference in the table. If you are between two sizes, pick the larger.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Measure at the end of the day when fingers are warm. Cold fingers shrink by half a size.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list -->


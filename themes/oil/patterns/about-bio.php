<p class="has-large-font-size">Agnes Brekke (b. 1979, Bergen) is a painter. She has lived in Edinburgh since 1998 and works in a top-floor studio in Leith, in the flat she also lives in.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p class="">She paints rooms, mostly the same four, at different times of day, and the streets between her flat and the shore. Everything starts from life. She does not paint from photographs, which is also why she turns down house portraits of places she can't sit in.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p class="">Her paintings are in the Leith Civic Collection and in private collections in Scotland, Norway, Canada and Japan. She teaches a drawing class at Leith School of Art on Tuesday evenings in term time.</p>

<div class="wp-block-column"><!-- wp:heading {"level":5} -->
<h5 class="wp-block-heading">Water coming through</h5>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li>Turn off the stopcock. It is usually under the kitchen sink, sometimes where the pipe comes into the house.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Turn off the electrics at the fuse box if water is near lights or sockets.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Open the cold taps to drain the pipes.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list --></div>
<!-- /wp:column -->

<!-- wp:column -->
<div class="wp-block-column"><!-- wp:heading {"level":5} -->
<h5 class="wp-block-heading">Smell of gas</h5>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li>Open doors and windows. Don't use switches or anything that sparks.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Turn off the gas at the meter: the lever goes across the pipe.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Leave the house and call 0800 111 999. Then call us.</li>
<!-- /wp:list-item --></ol>

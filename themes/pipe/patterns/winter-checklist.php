<h3 class="wp-block-heading">Five things to check in October</h3>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li>Put the heating on for an hour before you need it. Better to find a fault now.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Bleed any radiator that is cold at the top.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Check the pressure gauge reads 1 to 1.5 bar when cold.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Lag the condensate pipe if it runs outside. A frozen one stops the boiler.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>Book the service before November, when everyone else does.</li>

<!-- wp:paragraph -->
<p>Labels and hardware tell you more than the cut. These are the clues we check first.</p>
<!-- /wp:paragraph -->

<!-- wp:group {"className":"is-style-rows","layout":{"type":"default"}} -->
<div class="wp-block-group is-style-rows"><!-- wp:group {"layout":{"type":"grid","columnCount":2,"minimumColumnWidth":"9rem"}} -->
<div class="wp-block-group"><!-- wp:paragraph -->
<p>Union label</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>A small cloth union tag in US workwear usually means before the late 1980s.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"layout":{"type":"grid","columnCount":2,"minimumColumnWidth":"9rem"}} -->
<div class="wp-block-group"><!-- wp:paragraph -->
<p>Care label</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>UK care labels became common in the early 1970s. None at all often means older.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"layout":{"type":"grid","columnCount":2,"minimumColumnWidth":"9rem"}} -->
<div class="wp-block-group"><!-- wp:paragraph -->
<p>Zip</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Metal zips with a maker's name on the pull point to the 50s and 60s. Plastic coil zips arrive in the 70s.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"layout":{"type":"grid","columnCount":2,"minimumColumnWidth":"9rem"}} -->
<div class="wp-block-group"><!-- wp:paragraph -->
<p>Size format</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Chest sizes in inches on women's clothes are usually pre-1970. Dress sizes 10 to 16 take over after that.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"layout":{"type":"grid","columnCount":2,"minimumColumnWidth":"9rem"}} -->
<div class="wp-block-group"><!-- wp:paragraph -->
<p>Stock number</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Army clothing carries a stock or contract number and a date stamp inside.</p>
<!-- /wp:paragraph --></div>

<h2 class="wp-block-heading">How we measure</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>We lay every piece flat on the cutting table, buttoned or zipped, and measure seam to seam.</p>
<!-- /wp:paragraph -->

<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li><strong>Chest:</strong> straight across from armpit to armpit. Double it for the full chest.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Shoulder:</strong> from one shoulder seam to the other, across the back.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Length:</strong> from the base of the collar at the back (the nape) to the hem.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Sleeve:</strong> from the shoulder seam to the end of the cuff.</li>
<!-- /wp:list-item --></ol>

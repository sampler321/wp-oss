<h3 class="wp-block-heading">How I do it</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p class="">Heat the oven to 180°C. Oil the tin and line the bottom with paper, because plum juice glues everything.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p class="">Whisk the flour, sugar, baking powder and cinnamon. Pour in the oil and oat milk and stir until there are no dry bits. It will be thick, like porridge you forgot about.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p class="">Spread it in the tin, push the plums in skin side down, close together, and scatter the extra sugar over. Bake for 50 minutes, until the edges are brown and the plums have slumped.</p>
<!-- /wp:paragraph -->


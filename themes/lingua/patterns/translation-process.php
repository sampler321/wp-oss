<h2 class="wp-block-heading">How a translation goes</h2>
<!-- /wp:heading -->

<!-- wp:list {"ordered":true,"className":"is-style-steps"} -->
<ol class="wp-block-list is-style-steps"><!-- wp:list-item -->
<li><strong>Sample.</strong> For books, I translate 2,000 words so you and the publisher can hear the voice before anyone signs.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Glossary.</strong> Terms, names and anything that repeats, agreed before chapter one.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>First draft.</strong> Close to the Portuguese. Ugly in places on purpose.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Questions.</strong> A list of queries for the author or editor, usually 20 to 40 for a novel.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Revision.</strong> Two passes on the English, one of them read aloud.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Proofs.</strong> I check the typeset pages. Most translators don't get asked; it is worth asking.</li>
<!-- /wp:list-item --></ol>

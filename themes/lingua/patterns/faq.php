<!-- wp:details -->
<details class="wp-block-details"><summary>Do you charge on the source or the target word count?</summary><!-- wp:paragraph -->
<p>Source. You know the price before I start, and it doesn't change because English came out longer.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can you work in InDesign?</summary><!-- wp:paragraph -->
<p>I can translate from an IDML export and give you back a file your designer can flow in. I don't do the layout.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Will my name or the author's be credited?</summary><!-- wp:paragraph -->
<p>For books I ask for a credit on the title page, which is normal practice. For academic articles, a line in the acknowledgements is enough.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Is my manuscript kept confidential?</summary><!-- wp:paragraph -->
<p>Yes. I don't upload clients' texts to online translation tools, and I will sign your NDA.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How do I pay?</summary><!-- wp:paragraph -->
<p>Bank transfer in euros or sterling, within 30 days of the invoice. Publishers usually pay half on signing and half on delivery.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can you interpret at a meeting?</summary><!-- wp:paragraph -->
<p>Occasionally, for small academic events in Porto, and only from Portuguese into English. For conferences you need a booth team, and I can recommend two.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

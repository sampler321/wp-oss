<p class="has-large-font-size">Noor Verbeek (b. 1986, Schiedam) makes documentaries and short fiction about people who work at night. She studied at the Netherlands Film Academy and lives in Delfshaven, Rotterdam.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>She runs Verbeek &amp; Tahiri Films with producer Youssef Tahiri from a former ship chandler's office on the Voorhaven. They make one feature every three years and a short in between. They finance through the Netherlands Film Fund, the Flanders Audiovisual Fund and whoever else will listen.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>She shoots without added light whenever she can, which is why most of her films look like 4am. She does not make commercials.</p>

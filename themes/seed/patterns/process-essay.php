<h2 class="wp-block-heading">Why Drift has red lines</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"fontSize":"large"} -->
<p class="has-large-font-size">For the first two hundred seeds, Drift was black only. The outputs looked like hair. Good hair, but hair.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>I added a second pen to break the texture: every seventeenth line in red. Seventeen because it is prime, so the red never lines up into stripes with anything else in the code. Below are seed 12 (before) and seed 725 (after).</p>

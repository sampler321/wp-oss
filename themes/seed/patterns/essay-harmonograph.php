<!-- wp:paragraph -->
<p>The code does one job: it picks how far to pull each pendulum and how much weight to add, from the seed. Then I let go and the drawing takes about four minutes. Friction does the rest, which is why the lines spiral inwards.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>A kitchen scale sets the weights to the gram. Without it, no two drawings from the same seed looked related.</p>

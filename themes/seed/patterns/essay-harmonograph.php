<h2 class="wp-block-heading">A harmonograph from two bicycle wheels</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"fontSize":"large"} -->
<p class="has-large-font-size">Knot is drawn by a machine, not a plotter. Two pendulums hang from bicycle wheel hubs; one moves the paper, one moves the pen.</p>

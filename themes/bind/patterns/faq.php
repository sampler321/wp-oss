<details class="wp-block-details"><summary>Can you make my book look new?</summary><!-- wp:paragraph -->
<p>We can, but we usually advise against it. A rebacked book with its old boards keeps its history and most of its value.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you buy or value old books?</summary><!-- wp:paragraph -->
<p>No. For valuations, ask an antiquarian bookseller. Antykwariat Rara on Szewska is a good start.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can you bind my thesis today?</summary><!-- wp:paragraph -->
<p>Wire and thermal bindings, yes, if the PDF reaches us by noon. Hard cases take three days.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Will you post a book back to me?</summary><!-- wp:paragraph -->
<p>Yes, within Poland with InPost, packed between boards. Outside Poland by courier, quoted per parcel.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you take card?</summary><!-- wp:paragraph -->
<p>Yes, and BLIK. No card payments under 20 zł.</p>

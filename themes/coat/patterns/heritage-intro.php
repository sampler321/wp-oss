<!-- wp:paragraph -->
<p>Half of Dublin 7 was built before 1900, and a lot of it is protected. We strip sashes back to the timber, re-putty the glass, and paint with linseed oil paint where the conservation officer asks for it.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Anything painted before 1970 probably has lead in it. We test first, then wet-sand or use a heat gun at low temperature with extraction. No dry sanding, ever, and we tell you before we start.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->

<h2 class="wp-block-heading">Questions people ask</h2>
<!-- /wp:heading -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do we need to move out?</summary><!-- wp:paragraph -->
<p>No. We do one room at a time and put it back before we start the next. Kitchens are the exception: you will cook on a camping stove for about a week, or eat out.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How long does the smell last?</summary><!-- wp:paragraph -->
<p>A day with the windows open. We use water-based paint indoors unless an old surface needs oil.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you supply the paint?</summary><!-- wp:paragraph -->
<p>Yes, at trade price, and it is in the quote. If you already have tins, we will use them.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you take a deposit?</summary><!-- wp:paragraph -->
<p>Only for kitchens and jobs over €3,000: 20% to book the dates, the rest when we finish.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can the dog stay?</summary><!-- wp:paragraph -->
<p>Of course. Wet paint and tails don't mix, so we will ask you to keep doors shut.</p>
<!-- /wp:paragraph --></details>

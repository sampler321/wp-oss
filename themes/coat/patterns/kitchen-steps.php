<ol class="wp-block-list"><!-- wp:list-item -->
<li>Day 1: doors and drawers labelled, hinges bagged, everything degreased twice.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Day 2: sanded, scuffs filled, primed with a bonding primer for laminate or oil primer for timber.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Days 3 to 5: two coats of eggshell by brush, a light sand between them.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Day 6: handles back on, doors rehung and lined up, touch-ups done.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Day 7 (sometimes): the island, if it gets a different colour.</li>
